-- 0015_operator_requests.sql — заявки операторов, QR цехов, связь заявки с нарядом (M7).
--
-- Оператор сообщает о поломке по QR. Без входа он обязательно указывает ФИО.
-- Заявку без входа принимает серверный маршрут (app/api/requests), а он вызывает
-- submit_operator_request служебным ключом. Прямой записи в таблицу у анонима нет.
-- Наряд из заявки выдаёт только мастер.

-- ============================================================
-- 1. QR цехов
-- ============================================================
alter table sections add column qr_code text unique;

update sections set qr_code = case name
  when 'Участок дробления'          then 'SEC-DRB'
  when 'Участок обогащения'         then 'SEC-OBG'
  when 'Участок сушки и упаковки'   then 'SEC-SUSH'
  when 'Ремонтно-механический цех'  then 'SEC-RMC'
end
where qr_code is null;

-- ============================================================
-- 2. Поля заявки
-- ============================================================
-- Номер заявки для человека: «Заявка №214».
alter table requests add column number bigint generated by default as identity (start with 200);
alter table requests add column section_id uuid references sections(id);
alter table requests add column machine_state text check (machine_state in ('stopped', 'defect'));
alter table requests add column reporter_name text;        -- ФИО оператора без входа
alter table requests add column device_id text;            -- случайный номер телефона оператора для «Мои заявки»
alter table requests add column dismiss_reason text;
alter table requests add column order_id uuid references work_orders(id);  -- наряд, выданный по заявке

-- Без входа автор не известен, тогда ФИО обязательно.
alter table requests alter column created_by drop not null;
alter table requests add constraint request_author check (
  created_by is not null or (reporter_name is not null and length(btrim(reporter_name)) >= 3)
);
-- Отклонённая заявка всегда с причиной.
alter table requests add constraint request_dismiss_reason check (
  status <> 'dismissed' or (dismiss_reason is not null and length(btrim(dismiss_reason)) > 0)
);

create index requests_device_idx on requests(device_id, created_at desc) where device_id is not null;

alter table work_orders add column request_id uuid references requests(id);

-- Заявки появляются у мастера без обновления страницы.
alter publication supabase_realtime add table requests;

-- ============================================================
-- 3. Заявка оператора
-- ============================================================
-- p_code — код QR машины или цеха (или инвентарный номер с таблички).
-- p_author — сотрудник с ролью «Оператор», если он вошёл; иначе null и обязательно p_reporter_name.
-- Ограничение частоты: не больше 5 заявок с одного телефона за 10 минут.
create function submit_operator_request(
  p_code          text,
  p_description   text,
  p_machine_state text,
  p_reporter_name text,
  p_device_id     text,
  p_author        uuid default null,
  p_equipment_id  uuid default null,
  p_photo_path    text default null
) returns table (id uuid, number bigint)
language plpgsql security definer set search_path = public as $$
declare
  v_equipment equipment;
  v_section   sections;
  v_id        uuid;
  v_number    bigint;
begin
  if p_description is null or length(btrim(p_description)) < 3 then
    raise exception 'Опишите, что случилось' using errcode = '22023';
  end if;
  if p_author is null and (p_reporter_name is null or array_length(string_to_array(regexp_replace(btrim(p_reporter_name), ' +', ' ', 'g'), ' '), 1) < 2) then
    raise exception 'Укажите фамилию и имя' using errcode = '22023';
  end if;
  if p_device_id is null or length(p_device_id) < 8 then
    raise exception 'Нет номера телефона' using errcode = '22023';
  end if;
  if (select count(*) from requests r where r.device_id = p_device_id and r.created_at > now() - interval '10 minutes') >= 5 then
    raise exception 'Слишком много заявок подряд. Подождите несколько минут' using errcode = '22023';
  end if;

  -- Настоящий QR: машина или цех из справочника.
  select * into v_equipment from equipment e where e.qr_code = p_code or e.inventory_no = p_code;
  if v_equipment.id is null then
    select * into v_section from sections s where s.qr_code = p_code;
    if v_section.id is null then
      raise exception 'QR-код не найден' using errcode = 'P0002';
    end if;
    -- По QR цеха машину выбирают из списка цеха.
    if p_equipment_id is not null then
      select * into v_equipment from equipment e where e.id = p_equipment_id and e.section_id = v_section.id;
    end if;
  end if;

  insert into requests (equipment_id, section_id, description, machine_state, reporter_name,
                        device_id, created_by, photo_path)
  values (v_equipment.id, coalesce(v_equipment.section_id, v_section.id), btrim(p_description),
          case when p_machine_state in ('stopped', 'defect') then p_machine_state end,
          nullif(btrim(coalesce(p_reporter_name, '')), ''), p_device_id, p_author, p_photo_path)
  returning requests.id, requests.number into v_id, v_number;

  return query select v_id, v_number;
end;
$$;

-- Только сервер со служебным ключом. Ни анониму, ни вошедшему напрямую.
revoke execute on function submit_operator_request(text, text, text, text, text, uuid, uuid, text) from public, anon, authenticated;
grant execute on function submit_operator_request(text, text, text, text, text, uuid, uuid, text) to service_role;

-- «Мои заявки» оператора без входа: по номеру телефона. Без имён исполнителей.
create function operator_requests_by_device(p_device_id text)
returns table (
  id uuid, number bigint, created_at timestamptz, status request_status, description text,
  machine_state text, equipment_name text, section_name text, order_number bigint, dismiss_reason text
)
language sql stable security definer set search_path = public as $$
  select r.id, r.number, r.created_at, r.status, r.description, r.machine_state,
         e.name, s.name, o.number, r.dismiss_reason
    from requests r
    left join equipment e on e.id = r.equipment_id
    left join sections s on s.id = r.section_id
    left join work_orders o on o.id = r.order_id
   where r.device_id = p_device_id and length(p_device_id) >= 8
   order by r.created_at desc
   limit 30
$$;

revoke execute on function operator_requests_by_device(text) from public, anon, authenticated;
grant execute on function operator_requests_by_device(text) to service_role;

-- ============================================================
-- 4. Мастер обрабатывает заявку
-- ============================================================
-- Отклонить — только с причиной. Выдать наряд — заявка связывается с нарядом в обе стороны.
-- Новая функция вместо resolve_request (0011): старая не удаляется, у неё забраны права.
create function decide_request(
  p_request_id uuid,
  p_status     request_status,
  p_reason     text default null,
  p_order_id   uuid default null
) returns void
language plpgsql security definer set search_path = public as $$
begin
  if app.auth_role() is distinct from 'master' then
    raise exception 'Заявку обрабатывает мастер' using errcode = '42501';
  end if;
  if p_status = 'new' then
    raise exception 'Укажите, что сделать с заявкой' using errcode = '22023';
  end if;
  if p_status = 'dismissed' and (p_reason is null or length(btrim(p_reason)) = 0) then
    raise exception 'Нужно указать причину' using errcode = '22023';
  end if;

  update requests
     set status = p_status,
         dismiss_reason = case when p_status = 'dismissed' then btrim(p_reason) end,
         order_id = case when p_status = 'converted' then p_order_id end
   where id = p_request_id and status = 'new';
  if not found then
    raise exception 'Заявка не найдена или уже обработана' using errcode = 'P0002';
  end if;

  if p_status = 'converted' and p_order_id is not null then
    update work_orders set request_id = p_request_id where id = p_order_id and request_id is null;
  end if;
end;
$$;

revoke execute on function decide_request(uuid, request_status, text, uuid) from public, anon;
grant execute on function decide_request(uuid, request_status, text, uuid) to authenticated;
revoke execute on function resolve_request(uuid, request_status) from authenticated;
